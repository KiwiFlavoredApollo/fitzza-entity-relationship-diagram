// Convert the canonical PlantUML model using Node.js built-ins only.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(resolve(root, 'fitzza-erd.puml'), 'utf8').replaceAll('\r\n', '\n');
const tables = new Map();
const domains = new Map();
const quote = value => value.replaceAll('"', "'");
for (const pkg of source.matchAll(/^package "([^"]+)" \{\n(.*?)^\}/gms)) {
  const aliases = [];
  for (const entity of pkg[2].matchAll(/^  entity "([^"]+)" as (\w+)([^\n]*?) \{\n(.*?)^  \}/gms)) {
    const [, label, alias, , body] = entity;
    const columns = [];
    const notes = [];
    for (const line of body.split('\n')) {
      const column = line.match(/^\s*(\*)?\s*(\w+)\s*:\s*(.+)$/);
      if (column) {
        const [, required, name, spec] = column;
        const type = spec.match(/\b(INT|BIGINT|VARCHAR(?:\(\d+\))?|FLOAT|JSON|TEXT|DATETIME|BOOLEAN|ENUM)\b(?:\(\d+\))?/i)?.[0] ?? 'UNSPECIFIED';
        const keys = [];
        if (/\bPK\b/.test(spec)) keys.push('PK');
        if (/\bFK\b/.test(spec)) keys.push('FK');
        if (/\bUNIQUE\b/.test(spec)) keys.push('UK');
        const details = `${required && !spec.includes('NOT NULL') ? 'NOT NULL; ' : ''}${spec}`;
        columns.push({ name, keys, line: `        ${type} ${name}${keys.length ? ` ${keys.join(', ')}` : ''} "${quote(details)}"` });
      } else if (line.trim().startsWith("'")) {
        notes.push(line.trim().slice(1).trim());
      } else if (line.trim() && line.trim() !== '--') {
        notes.push(`Constraint: ${line.trim()}`);
      }
    }
    tables.set(alias, { domain: pkg[1], label, columns, notes });
    aliases.push(alias);
  }
  domains.set(pkg[1], aliases);
}
const relations = [...source.matchAll(/^(\w+) ([|o{}.-]+) (\w+) : "([^"]+)"$/gm)]
  .map(([, parent, connector, child, label]) => ({ parent, connector, child, label }));
assert.equal(tables.size, 29, 'Review parser: expected 29 tables');
assert.equal([...tables.values()].reduce((sum, t) => sum + t.columns.length, 0), 203, 'Review parser: expected 203 columns');
assert.equal(relations.length, 53, 'Review parser: expected 53 relationships');
for (const r of relations) {
  assert(tables.has(r.parent) && tables.has(r.child), 'Unknown relationship endpoint');
  assert(tables.get(r.child).columns.some(c => c.name === r.label.split(' ')[0]), `Unknown reference column: ${r.label}`);
}
const output = resolve(root, 'diagrams', 'mermaid');
mkdirSync(output, { recursive: true });
function diagram(aliases, edges, primaryOnly = false) {
  const lines = ['%% Generated by scripts/generate_mermaid.mjs; edit fitzza-erd.puml instead.', 'erDiagram', '    direction TB'];
  for (const alias of aliases) {
    const t = tables.get(alias);
    lines.push(`    %% ${t.domain}: ${t.label.replaceAll('\\n', ' / ')}`);
    if (!primaryOnly) lines.push(...t.notes.map(note => `    %% ${note}`));
    lines.push(`    ${alias} {`, ...t.columns.filter(c => !primaryOnly || c.keys.includes('PK')).map(c => c.line), '    }');
  }
  lines.push(...edges.map(r => `    ${r.parent} ${r.connector} ${r.child} : "${quote(r.label)}"`), '');
  return lines.join('\n');
}
function writePair(directory, name, title, code) {
  writeFileSync(resolve(directory, `${name}.mmd`), code);
  writeFileSync(resolve(directory, `${name}.md`), `# ${title}\n\n자동 생성된 Mermaid ERD입니다. 원본: \`fitzza-erd.puml\`.\n\n실선은 명시된 FK, 점선은 논리적·조건부 참조입니다. PK/FK/UK는 기본 키/외래 키/단일 컬럼 UNIQUE를 의미합니다. 복합 UNIQUE와 원본 설명은 Mermaid 소스의 주석에 보존합니다. 컬럼 설명에는 원본 타입과 제약조건을 표시합니다. UNSPECIFIED는 원본에 타입이 명시되지 않은 컬럼입니다.\n\n\`||\`: 정확히 1개, \`|o\`/\`o|\`: 0~1개, \`o{\`: 0개 이상. 점선/실선은 원본 참조 구분을 유지하며 Mermaid의 식별 관계 의미를 별도로 추론하지 않습니다.\n\n\`\`\`mermaid\n${code}\`\`\`\n`);
}
writePair(root, 'fitzza-erd', 'Fitzza 전체 ERD', diagram([...tables.keys()], relations));
writePair(output, 'fitzza-overview', 'Fitzza 테이블 개요 (PK)', diagram([...tables.keys()], [], true));
const assigned = [];
for (const [domain, aliases] of domains) {
  const edges = relations.filter(r => aliases.includes(r.child));
  assigned.push(...edges);
  const endpoints = new Set([...aliases, ...edges.flatMap(r => [r.parent, r.child])]);
  writePair(output, domain, `Fitzza ERD — ${domain}`, diagram([...endpoints], edges));
}
assert.equal(new Set(assigned).size, relations.length, 'Missing relationships in domain views');
console.log(`Generated Mermaid: ${tables.size} tables, 203 columns, ${relations.length} relationships, ${domains.size} domain views.`);
