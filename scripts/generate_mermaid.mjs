// Generate Markdown and domain views from the canonical Mermaid source.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(resolve(root, 'fitzza-erd.mmd'), 'utf8').replaceAll('\r\n', '\n');
const tables = new Map();
const domains = new Map();
const quote = value => value.replaceAll('"', "'");
for (const entity of source.matchAll(/^    %% (\w+_db): ([^\n]+)\n((?:    %%[^\n]*\n)*)    (\w+) \{\n(.*?)^    \}/gms)) {
  const [, domain, label, comments, alias, body] = entity;
  const columns = body.split('\n').filter(line => line.trim()).map(line => {
    const match = line.match(/^\s*\S+\s+(\w+)(?:\s+((?:PK|FK|UK)(?:,\s*(?:PK|FK|UK))*))?(?:\s+"[^"]*")?$/);
    assert(match, `Unsupported column: ${line}`);
    return { name: match[1], keys: match[2]?.split(/,\s*/) ?? [], line };
  });
  const notes = comments.split('\n').filter(Boolean).map(line => line.replace(/^    %% ?/, ''));
  tables.set(alias, { domain, label, columns, notes });
  if (!domains.has(domain)) domains.set(domain, []);
  domains.get(domain).push(alias);
}
const relations = [...source.matchAll(/^    (\w+) ([|o{}.-]+) (\w+) : "([^"]+)"$/gm)]
  .map(([, parent, connector, child, label]) => ({ parent, connector, child, label }));
assert.equal(tables.size, 29, 'Review parser: expected 29 tables');
assert.equal([...tables.values()].reduce((sum, t) => sum + t.columns.length, 0), 203, 'Review parser: expected 203 columns');
assert.equal(relations.length, 53, 'Review parser: expected 53 relationships');
for (const r of relations) {
  assert(tables.has(r.parent) && tables.has(r.child), 'Unknown relationship endpoint');
  assert(tables.get(r.child).columns.some(c => c.name === r.label.split(' ')[0]), `Unknown reference column: ${r.label}`);
}
const output = resolve(root, 'diagrams', 'mermaid');
mkdirSync(output, { recursive: true });
function diagram(aliases, edges, primaryOnly = false) {
  const lines = ['%% Generated by scripts/generate_mermaid.mjs; edit fitzza-erd.mmd instead.', 'erDiagram', '    direction TB'];
  for (const alias of aliases) {
    const t = tables.get(alias);
    lines.push(`    %% ${t.domain}: ${t.label.replaceAll('\\n', ' / ')}`);
    if (!primaryOnly) lines.push(...t.notes.map(note => `    %% ${note}`));
    lines.push(`    ${alias} {`, ...t.columns.filter(c => !primaryOnly || c.keys.includes('PK')).map(c => c.line), '    }');
  }
  lines.push(...edges.map(r => `    ${r.parent} ${r.connector} ${r.child} : "${quote(r.label)}"`), '');
  return lines.join('\n');
}
function writePair(directory, name, title, code) {
  if (directory !== root) writeFileSync(resolve(directory, `${name}.mmd`), code);
  writeFileSync(resolve(directory, `${name}.md`), `# ${title}\n\n자동 생성된 Mermaid ERD입니다. 원본: \`fitzza-erd.mmd\`.\n\n실선은 명시된 FK, 점선은 논리적·조건부 참조입니다. PK/FK/UK는 기본 키/외래 키/단일 컬럼 UNIQUE를 의미합니다. 복합 UNIQUE와 원본 설명은 Mermaid 소스의 주석에 보존합니다. 컬럼 설명에는 원본 타입과 제약조건을 표시합니다. UNSPECIFIED는 원본에 타입이 명시되지 않은 컬럼입니다.\n\n\`||\`: 정확히 1개, \`|o\`/\`o|\`: 0~1개, \`o{\`: 0개 이상. 점선/실선은 원본 참조 구분을 유지하며 Mermaid의 식별 관계 의미를 별도로 추론하지 않습니다.\n\n\`\`\`mermaid\n${code}\`\`\`\n`);
}
writePair(root, 'fitzza-erd', 'Fitzza 전체 ERD', diagram([...tables.keys()], relations));
writePair(output, 'fitzza-overview', 'Fitzza 테이블 개요 (PK)', diagram([...tables.keys()], [], true));
const assigned = [];
for (const [domain, aliases] of domains) {
  const edges = relations.filter(r => aliases.includes(r.child));
  assigned.push(...edges);
  const endpoints = new Set([...aliases, ...edges.flatMap(r => [r.parent, r.child])]);
  writePair(output, domain, `Fitzza ERD — ${domain}`, diagram([...endpoints], edges));
}
assert.equal(new Set(assigned).size, relations.length, 'Missing relationships in domain views');
console.log(`Generated Mermaid: ${tables.size} tables, 203 columns, ${relations.length} relationships, ${domains.size} domain views.`);
