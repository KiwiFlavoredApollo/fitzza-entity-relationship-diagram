// Generate readable views from the canonical ERD with Node.js built-ins only.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import assert from 'node:assert/strict';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(resolve(root, 'fitzza-erd.puml'), 'utf8').replaceAll('\r\n', '\n');
const output = resolve(root, 'diagrams');
const style = `left to right direction
skinparam backgroundColor #FFFFFF
skinparam defaultFontName SansSerif
skinparam linetype ortho
skinparam shadowing false
skinparam packageStyle rectangle
skinparam nodesep 65
skinparam ranksep 85
skinparam entityBackgroundColor #F8FAFC
skinparam entityBorderColor #475569
hide circle`;
const domains = new Map();
const tables = new Map();
for (const pkg of source.matchAll(/^package "([^"]+)" \{\n(.*?)^\}/gms)) {
  const aliases = [];
  for (const entity of pkg[2].matchAll(/^  entity "([^"]+)" as (\w+)([^\n]*?) \{\n(.*?)^  \}/gms)) {
    const [, label, alias, suffix, columns] = entity;
    tables.set(alias, { domain: pkg[1], label, suffix, columns, definition: entity[0] });
    aliases.push(alias);
  }
  domains.set(pkg[1], aliases);
}
const relations = [...source.matchAll(/^(\w+) ([|o{}.-]+) (\w+) : "([^"]+)"$/gm)]
  .map(([line, parent, connector, child, label]) => ({ line, parent, connector, child, label }));
assert.equal(tables.size, 29, 'Source structure changed; review parser');
assert.equal(relations.length, 53, 'Source structure changed; review parser');
for (const r of relations) assert(tables.has(r.parent) && tables.has(r.child), r.line);
const primaryKeys = table => table.columns.split('\n').filter(line => /: PK(?:,|$)/.test(line));
const legend = source.slice(source.indexOf('legend bottom left'), source.indexOf('@enduml'));
const generated = "' Generated by scripts/generate_views.mjs; edit fitzza-erd.puml instead.";
mkdirSync(output, { recursive: true });
const assigned = [];
for (const [domain, aliases] of domains) {
  // Each edge appears in the view of its referencing (child) table's domain.
  const selected = relations.filter(r => aliases.includes(r.child));
  assigned.push(...selected.map(r => r.line));
  const external = [...new Set(selected.map(r => r.parent))].filter(a => !aliases.includes(a)).sort();
  const lines = [`@startuml ${domain}`, generated, style, `title Fitzza ERD — ${domain}`, `package "${domain}" {`,
    ...aliases.map(a => tables.get(a).definition), '}'];
  if (external.length) {
    lines.push('package "외부 참조 (참조 키만 표시)" {');
    for (const alias of external) {
      const table = tables.get(alias);
      lines.push(`  entity "${table.label}\\n[${table.domain}]" as ${alias} #EEF2FF {`, ...primaryKeys(table), '  }');
    }
    lines.push('}');
  }
  lines.push(...selected.map(r => r.line), legend, '@enduml', '');
  writeFileSync(resolve(output, `${domain}.puml`), lines.join('\n'));
}
assert.deepEqual(assigned.sort(), relations.map(r => r.line).sort(), 'Missing or duplicate relationships');
const overview = ['@startuml fitzza-overview', generated, style, 'title Fitzza ERD — 도메인 개요', 'top to bottom direction'];
for (const [domain, aliases] of domains) {
  overview.push(`package "${domain}" as ${domain} {`);
  for (const alias of aliases) {
    const table = tables.get(alias);
    overview.push(`  entity "${table.label}" as ${alias}${table.suffix} {`, ...primaryKeys(table), '  }');
  }
  overview.push(...relations.filter(r => aliases.includes(r.parent) && aliases.includes(r.child)).map(r => r.line), '}');
}
// Arrange independent domain panels into three columns instead of one long row.
const domainNames = [...domains.keys()];
for (let i = 0; i < domainNames.length; i++) {
  if (i % 3 < 2 && i + 1 < domainNames.length)
    overview.push(`${domainNames[i]} -[hidden]right- ${domainNames[i + 1]}`);
  if (i + 3 < domainNames.length)
    overview.push(`${domainNames[i]} -[hidden]down- ${domainNames[i + 3]}`);
}
overview.push('legend bottom left', '  개요: 기본 키(PK)와 도메인 내부 관계만 표시',
  '  실선: 명시된 외래 키 관계 / 점선: 논리적·조건부 참조',
  '  ||: 필수 참조 / |o: 선택 참조 / o{: 0개 이상 / o|: 최대 1개',
  '  회색 테이블: 명세서에서 미사용으로 표시된 테이블',
  '  도메인 간 관계와 전체 컬럼: diagrams/<domain>.puml 참조',
  '  모든 관계를 한 장에 표시: fitzza-erd.puml 참조', 'endlegend', '@enduml', '');
writeFileSync(resolve(output, 'fitzza-overview.puml'), overview.join('\n'));
console.log(`Generated overview and ${domains.size} domain views; preserved ${tables.size} tables and ${relations.length} relationships.`);
